export const sectionBySlug = Object.fromEntries(sections.map((s) => [s.slug, s]));

export const sectionSlugs = sections.map((s) => s.slug);

// Хлебные крошки раздела: «Главная / <раздел>».
export function crumbsFor(slug) {
  const section = sectionBySlug[slug];
  return [
    { href: '/', label: 'Главная' },
    { href: `/${slug}`, label: section.crumb },
  ];
}

// Метаданные раздела: уникальные title/description, канонический адрес
// на самого себя, OpenGraph — один в один как у страниц услуг.
export function sectionMetadata(slug) {
  const section = sectionBySlug[slug];
  const url = `${SITE}/${slug}`;

  return {
    title: section.title,
    description: section.description,
    alternates: { canonical: `/${slug}` },
    openGraph: {
      title: section.title,
      description: section.description,
      url,
      siteName: 'Доктор Маркарян',
      locale: 'ru_RU',
      type: 'website',
    },
  };
}
